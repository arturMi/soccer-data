from sqlalchemy import Column, Integer, String, ForeignKey, JSON
from sqlalchemy.ext.declarative import declarative_base

from model.match import Match

Base = declarative_base()


class MatchReport(Base):
    __tablename__ = 'match_report'

    id = Column(Integer, primary_key=True, autoincrement=True)
    website = Column(String, nullable=False)
    match_id = Column(Integer, ForeignKey(Match.id), nullable=False)
    # Home Columns
    home_average_age = Column(JSON)
    home_scores = Column(JSON)
    home_scores_ht = Column(JSON)
    home_ratings = Column(JSON)
    home_shots_total = Column(JSON)
    home_shots_on_target = Column(JSON)
    home_shots_off_target = Column(JSON)
    home_shots_blocked = Column(JSON)
    home_clearances = Column(JSON)
    home_interceptions = Column(JSON)
    home_possesion = Column(JSON)
    home_touches = Column(JSON)
    home_passes_total = Column(JSON)
    home_passes_accurate = Column(JSON)
    home_passes_key = Column(JSON)
    home_pass_success = Column(JSON)
    home_aerials_total = Column(JSON)
    home_aerials_won = Column(JSON)
    home_aerials_success = Column(JSON)
    home_offensive_aerials = Column(JSON)
    home_defensive_aerials = Column(JSON)
    home_corners_total = Column(JSON)
    home_throw_ins_total = Column(JSON)
    home_throw_ins_accurate = Column(JSON)
    home_fouls_commited = Column(JSON)
    home_tackles_total = Column(JSON)
    home_tackles_successful = Column(JSON)
    home_tackles_unsuccessful = Column(JSON)
    home_tackles_success = Column(JSON)
    home_dribbled_past = Column(JSON)
    home_dribbles_won = Column(JSON)
    home_dribbles_attempted = Column(JSON)
    home_dribbles_lost = Column(JSON)
    home_dribble_success = Column(JSON)
    home_dispossessed = Column(JSON)
    #Away Columns
    away_average_age = Column(JSON)
    away_scores = Column(JSON)
    away_scores_ht = Column(JSON)
    away_ratings = Column(JSON)
    away_shots_total = Column(JSON)
    away_shots_on_target = Column(JSON)
    away_shots_off_target = Column(JSON)
    away_shots_blocked = Column(JSON)
    away_clearances = Column(JSON)
    away_interceptions = Column(JSON)
    away_possesion = Column(JSON)
    away_touches = Column(JSON)
    away_passes_total = Column(JSON)
    away_passes_accurate = Column(JSON)
    away_passes_key = Column(JSON)
    away_pass_success = Column(JSON)
    away_aerials_total = Column(JSON)
    away_aerials_won = Column(JSON)
    away_aerials_success = Column(JSON)
    away_offensive_aerials = Column(JSON)
    away_defensive_aerials = Column(JSON)
    away_corners_total = Column(JSON)
    away_throw_ins_total = Column(JSON)
    away_throw_ins_accurate = Column(JSON)
    away_fouls_commited = Column(JSON)
    away_tackles_total = Column(JSON)
    away_tackles_successful = Column(JSON)
    away_tackles_unsuccessful = Column(JSON)
    away_tackles_success = Column(JSON)
    away_dribbled_past = Column(JSON)
    away_dribbles_won = Column(JSON)
    away_dribbles_attempted = Column(JSON)
    away_dribbles_lost = Column(JSON)
    away_dribble_success = Column(JSON)
    away_dispossessed = Column(JSON)

    def __init__(self, **kwargs):
        self.__dict__.update(kwargs)

    def __repr__(self):
        return self.website